/* ========== 手册正文 ==========
 * 【待填】——这是 L2 唯一需要你写的内容。
 *
 * 每个改法一篇，按 SECTION_OUTLINE 的六段写。
 * 写不出来的段就空着，页面上会显示「这段待填」——空着比编一个好。
 *
 * 建议的写法：
 *   - 用你自己的话，不要写成制度文本
 *   - 每段配一个你见过的真实例子（脱敏）
 *   - "什么是成功"和"怎么退回来"这两段最容易漏，但最值钱
 *
 * ------------------------------------------------------------
 * 评审标准（写完拿这六条过一遍）
 *
 * 1. 每篇必须能独立成立。
 *    用户每次只拿到一篇。他没见过病因编号、没见过内部文档、也没拿到别篇手册。
 *    所以「见 XX 那一篇」「上一轮说的」都是死引用。
 *    → 跑 node tools/check-manual-terms.js 查这一项。
 *
 * 2. 成功判据必须是「行为变了」，不是「结果好了」。
 *    结果受行情、成本、定价影响，好了也分不清是谁起的作用。
 *
 * 3. 判据要取在被激励的人身上，不能取在公司拍板的产物上。
 *    「明年的计划」「定下来的目标」是上面定的，跟你改没改机制没关系；
 *    「谁在抢什么活」「谁把什么让出去」才是被激励出来的。
 *
 * 4. 判据在旧机制下得是做不出来的。
 *    旧机制下本来就有的行为，改了之后还有，什么都证明不了。
 *
 * 5. 「坑」要写**这次改动的副作用**，不是「注意事项」。
 *    注意事项在前面几段已经说完了。副作用是它还没讲到、但一定会发生的：
 *    「**你做了 A，结果长出了 B**」。
 *    例：改成小组池 → 组和组之间的墙变厚了（原来跨组还能搭把手，
 *    现在帮别人等于让本组少拿）；换成增量基数 → 年底开始压单
 *    （把业绩推到下一年，让明年的增量好看）。
 *    一篇里没有这类事，那一段就空着——别用注意事项去填。
 *
 * 6. 「改错了」要分四类：诊断错了（换改法）/ 诊断不完整（加做一件事）/
 *    执行没做到位（补规则）/ 起反作用（才退）。四类的动作完全不同——
 *    混在一起，用户不知道该补、该换、还是该退。
 *
 *    「诊断不完整」是后加的：同一个病还有别的成因，下一步是**加做一件事**，
 *    不是换改法。跟「诊断错了」放一起会让人做错动作。
 *
 * 7. 成功判据不能写成「坏事没发生」。
 *    「没去找领导闹」「不再压单」这类比「发生了」弱得多——没发生可能是
 *    不敢、不在乎、或者根本没触发。**成功的证据必须多了一件好事，
 *    不是少了一件坏事。**「没发生」可以当排除条件，不能当成功判据。
 *
 * 8. 判据里的「有人问…」，要问方向。
 *    「做到什么程度能拿到」= 他在优化（好）；
 *    「这是怎么算的」= 他看不懂、或者不服（坏）。
 *    同一句话，两个相反的意思。
 *
 * 9. 每条「坑」都要有对应的做法，或者明说「这个坑只能靠注意」。
 *    坑指出了问题、做法里却没有对应的动作，等于把人扔在那儿。
 * ------------------------------------------------------------
 */
